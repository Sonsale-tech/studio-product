import React, { useState } from 'react';
import confetti from 'canvas-confetti';
import { TestSuite, StudentSubmission } from '../types';
import { MathText } from '../utils/latexRenderer';
import { CheckCircle2, XCircle, AlertCircle, RefreshCw, User, Award, Check, ChevronRight, HelpCircle } from 'lucide-react';

interface TestRunnerProps {
  testSuites: TestSuite[];
  onSaveSubmission: (submission: StudentSubmission) => void;
}

type RunnerScreen = 'student' | 'select' | 'quiz' | 'result';

export const TestRunner: React.FC<TestRunnerProps> = ({ testSuites, onSaveSubmission }) => {
  const [screen, setScreen] = useState<RunnerScreen>('student');
  const [studentName, setStudentName] = useState<string>('Rahul Sharma');
  const [rollNo, setRollNo] = useState<string>('XII-PHY-42');
  const [selectedTest, setSelectedTest] = useState<TestSuite | null>(null);
  const [currentQIndex, setCurrentQIndex] = useState<number>(0);
  const [selectedOption, setSelectedOption] = useState<string>('');
  const [studentAnswers, setStudentAnswers] = useState<string[]>([]);
  const [score, setScore] = useState<number>(0);
  const [savingState, setSavingState] = useState<'idle' | 'saving' | 'saved'>('idle');

  // Handle continuing from Student Info screen
  const handleContinueToTests = (e: React.FormEvent) => {
    e.preventDefault();
    if (!studentName.trim()) {
      alert('Please enter your Student Name.');
      return;
    }
    if (!rollNo.trim()) {
      alert('Please enter your Roll No.');
      return;
    }
    setScreen('select');
  };

  // Start test
  const handleStartTest = (test: TestSuite) => {
    setSelectedTest(test);
    setCurrentQIndex(0);
    setSelectedOption('');
    setStudentAnswers(new Array(test.questions.length).fill(''));
    setScore(0);
    setSavingState('idle');
    setScreen('quiz');
  };

  // Next question / Submit question
  const handleNextOrSubmit = () => {
    if (!selectedTest) return;

    if (!selectedOption) {
      alert('Please select an option before continuing.');
      return;
    }

    const updatedAnswers = [...studentAnswers];
    updatedAnswers[currentQIndex] = selectedOption;
    setStudentAnswers(updatedAnswers);

    if (currentQIndex === selectedTest.questions.length - 1) {
      // Calculate final score
      let finalScore = 0;
      selectedTest.questions.forEach((q, idx) => {
        if (updatedAnswers[idx] === q.answer) {
          finalScore += 1;
        }
      });
      setScore(finalScore);

      // Trigger confetti if scored well
      const percentage = (finalScore / selectedTest.questions.length) * 100;
      if (percentage >= 60) {
        try {
          confetti({
            particleCount: 80,
            spread: 70,
            origin: { y: 0.6 },
          });
        } catch {
          // ignore
        }
      }

      // Save submission record
      const newSubmission: StudentSubmission = {
        id: `sub-${Date.now()}`,
        timestamp: new Date().toLocaleString(),
        testName: selectedTest.name,
        rollNo: rollNo.trim(),
        studentName: studentName.trim(),
        score: finalScore,
        totalQuestions: selectedTest.questions.length,
        percentage: Number(percentage.toFixed(2)),
        studentAnswers: updatedAnswers,
      };

      setSavingState('saving');
      setTimeout(() => {
        onSaveSubmission(newSubmission);
        setSavingState('saved');
      }, 600);

      setScreen('result');
    } else {
      const nextIndex = currentQIndex + 1;
      setCurrentQIndex(nextIndex);
      setSelectedOption(updatedAnswers[nextIndex] || '');
    }
  };

  const handleOptionChange = (optionKey: string) => {
    setSelectedOption(optionKey);
  };

  const handleResetStudent = () => {
    setScreen('student');
  };

  const handleGoToTestSelection = () => {
    setScreen('select');
  };

  const currentQuestion = selectedTest?.questions[currentQIndex];
  const totalQ = selectedTest?.questions.length || 0;

  return (
    <div className="py-6 px-3 sm:px-6 max-w-4xl mx-auto">
      {/* Banner indicating Web App simulation */}
      <div className="mb-4 bg-amber-50 border border-amber-200 text-amber-900 rounded-xl p-3.5 flex items-center justify-between shadow-xs">
        <div className="flex items-center space-x-2.5">
          <span className="flex h-2.5 w-2.5 relative">
            <span className="animate-ping absolute inline-flex h-full w-full rounded-full bg-amber-400 opacity-75"></span>
            <span className="relative inline-flex rounded-full h-2.5 w-2.5 bg-amber-500"></span>
          </span>
          <span className="text-xs sm:text-sm font-medium">
            <strong>Live Google Apps Script Web App Simulator:</strong> Testing the student interface generated by <code className="bg-amber-100 px-1.5 py-0.5 rounded text-amber-950 font-mono text-xs">Code.gs</code> + <code className="bg-amber-100 px-1.5 py-0.5 rounded text-amber-950 font-mono text-xs">index.html</code>.
          </span>
        </div>
        <button
          onClick={handleResetStudent}
          className="text-xs bg-white text-slate-700 hover:bg-slate-50 border border-slate-200 px-2.5 py-1 rounded font-semibold transition"
        >
          Reset Session
        </button>
      </div>

      {/* Embedded Web App Frame mimicking original styling */}
      <div className="bg-[#fff9cc] p-4 sm:p-8 rounded-2xl border-2 border-blue-950/20 shadow-md">
        {/* Main Title */}
        <div className="text-center mb-6">
          <h1 className="text-xl sm:text-2xl font-bold text-[#003366] leading-snug">
            Std. XII Physics<br />
            Semiconductor MCQ Practice Test
          </h1>
        </div>

        {/* 1. STUDENT SCREEN */}
        {screen === 'student' && (
          <div className="bg-white border-2 border-[#003366] rounded-xl p-6 sm:p-8 shadow-sm">
            <div className="flex items-center space-x-2 mb-4 border-b border-slate-100 pb-3">
              <User className="w-5 h-5 text-[#003366]" />
              <h2 className="text-xl font-bold text-[#003366]">Student Information</h2>
            </div>

            <form onSubmit={handleContinueToTests} className="space-y-4">
              <div>
                <label className="block text-sm font-bold text-[#003366] mb-1">
                  Student Name
                </label>
                <input
                  type="text"
                  id="input-student-name"
                  value={studentName}
                  onChange={(e) => setStudentName(e.target.value)}
                  placeholder="Enter your full name"
                  className="w-full px-4 py-3 border-1.5 border-slate-400 rounded-lg text-base focus:outline-none focus:border-[#003366] focus:ring-1 focus:ring-[#003366]"
                  required
                />
              </div>

              <div>
                <label className="block text-sm font-bold text-[#003366] mb-1">
                  Roll No.
                </label>
                <input
                  type="text"
                  id="input-student-roll"
                  value={rollNo}
                  onChange={(e) => setRollNo(e.target.value)}
                  placeholder="Enter your Roll No."
                  className="w-full px-4 py-3 border-1.5 border-slate-400 rounded-lg text-base focus:outline-none focus:border-[#003366] focus:ring-1 focus:ring-[#003366]"
                  required
                />
              </div>

              <div className="text-center pt-4">
                <button
                  type="submit"
                  id="btn-continue-tests"
                  className="w-full sm:w-auto bg-[#003366] hover:bg-[#005599] text-white px-8 py-3.5 rounded-lg font-bold text-base transition shadow cursor-pointer"
                >
                  CONTINUE
                </button>
              </div>
            </form>
          </div>
        )}

        {/* 2. TEST SELECTION SCREEN */}
        {screen === 'select' && (
          <div className="bg-white border-2 border-[#003366] rounded-xl p-6 sm:p-8 shadow-sm">
            <div className="flex items-center justify-between border-b border-slate-200 pb-3 mb-4">
              <h2 className="text-xl font-bold text-[#003366]">Select Practice Test</h2>
              <button
                onClick={() => setScreen('student')}
                className="text-xs text-slate-500 hover:text-slate-800 underline"
              >
                Change Student
              </button>
            </div>

            <div className="bg-blue-50/60 border border-blue-100 rounded-lg p-3 text-center mb-5 text-[#003366] font-medium text-sm">
              Student: <strong>{studentName}</strong> &bull; Roll No.: <strong>{rollNo}</strong>
            </div>

            <div className="space-y-4">
              {testSuites.map((test, index) => (
                <div
                  key={test.id}
                  className="bg-[#e6ffff] border border-cyan-200 rounded-xl p-5 transition hover:shadow-md"
                >
                  <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3">
                    <div>
                      <div className="flex items-center space-x-2">
                        <span className="bg-[#003366] text-white text-xs font-bold px-2 py-0.5 rounded">
                          Test {index + 1}
                        </span>
                        <span className="text-xs font-semibold text-slate-500">
                          {test.questions.length} Questions
                        </span>
                      </div>
                      <h3 className="text-base sm:text-lg font-bold text-[#003366] mt-1.5">
                        {test.name}
                      </h3>
                      {test.description && (
                        <p className="text-xs sm:text-sm text-slate-600 mt-1">
                          {test.description}
                        </p>
                      )}
                    </div>
                    <button
                      id={`btn-start-test-${index}`}
                      onClick={() => handleStartTest(test)}
                      className="bg-[#003366] hover:bg-[#005599] text-white px-6 py-2.5 rounded-lg font-bold text-sm transition cursor-pointer whitespace-nowrap shadow-xs"
                    >
                      START TEST
                    </button>
                  </div>
                </div>
              ))}
            </div>
          </div>
        )}

        {/* 3. QUESTION SCREEN */}
        {screen === 'quiz' && selectedTest && currentQuestion && (
          <div className="bg-white border-2 border-[#003366] rounded-xl p-6 sm:p-8 shadow-sm">
            {/* Header info */}
            <div className="flex items-center justify-between text-xs sm:text-sm text-slate-500 border-b border-slate-100 pb-3 mb-4">
              <span className="font-semibold text-[#003366] truncate max-w-[200px] sm:max-w-md">
                {selectedTest.name}
              </span>
              <span>
                Student: <strong>{studentName}</strong>
              </span>
            </div>

            {/* Progress bar */}
            <div className="w-full bg-slate-100 rounded-full h-2 mb-5 overflow-hidden">
              <div
                className="bg-[#003366] h-2 rounded-full transition-all duration-300"
                style={{ width: `${((currentQIndex + 1) / totalQ) * 100}%` }}
              ></div>
            </div>

            {/* Question Number */}
            <div className="text-center text-[#003366] font-bold text-base sm:text-lg mb-4">
              Question {currentQIndex + 1} / {totalQ}
            </div>

            {/* Question Text with KaTeX LaTeX */}
            <div className="text-base sm:text-lg leading-relaxed text-slate-900 mb-5 p-4 bg-slate-50/70 rounded-xl border border-slate-200">
              <MathText text={currentQuestion.q} />
            </div>

            {/* Optional Image / Diagram */}
            {currentQuestion.image && (
              <div className="mb-5 text-center">
                <img
                  src={currentQuestion.image}
                  alt="Question Diagram"
                  className="max-h-64 mx-auto rounded-lg border border-slate-300 shadow-xs"
                  onError={(e) => {
                    (e.target as HTMLImageElement).style.display = 'none';
                  }}
                />
              </div>
            )}

            {/* Options List */}
            <div className="space-y-3 mb-6" role="radiogroup">
              {currentQuestion.options.map((optionText, optIdx) => {
                const letter = String.fromCharCode(65 + optIdx); // 'A', 'B', 'C', 'D'
                const isChecked = selectedOption === letter;

                return (
                  <label
                    key={optIdx}
                    id={`opt-label-${letter}`}
                    onClick={() => handleOptionChange(letter)}
                    className={`flex items-start p-3.5 sm:p-4 rounded-xl border-1.5 cursor-pointer transition text-sm sm:text-base ${
                      isChecked
                        ? 'bg-[#d0f7f7] border-[#003366] font-semibold text-slate-900 shadow-xs'
                        : 'bg-[#e6ffff] border-cyan-200 hover:bg-[#d8f5f5] text-slate-800'
                    }`}
                  >
                    <input
                      type="radio"
                      name="test-question-answer"
                      value={letter}
                      checked={isChecked}
                      onChange={() => handleOptionChange(letter)}
                      className="mt-1 mr-3 w-4 h-4 text-[#003366] focus:ring-[#003366] cursor-pointer"
                    />
                    <div className="flex-1">
                      <span className="font-bold text-[#003366] mr-2">{letter}.</span>
                      <MathText text={optionText} />
                    </div>
                  </label>
                );
              })}
            </div>

            {/* Action Buttons */}
            <div className="flex flex-col sm:flex-row items-center justify-between gap-3 pt-3 border-t border-slate-100">
              <button
                type="button"
                onClick={handleGoToTestSelection}
                className="text-xs text-slate-500 hover:text-slate-800"
              >
                &larr; Exit to Test Selection
              </button>

              <button
                type="button"
                id="btn-next-question"
                onClick={handleNextOrSubmit}
                className="w-full sm:w-auto bg-[#003366] hover:bg-[#005599] text-white px-8 py-3 rounded-lg font-bold text-base transition shadow cursor-pointer flex items-center justify-center space-x-2"
              >
                <span>{currentQIndex === totalQ - 1 ? 'SUBMIT TEST' : 'NEXT'}</span>
                <ChevronRight className="w-4 h-4" />
              </button>
            </div>
          </div>
        )}

        {/* 4. RESULT SCREEN WITH REVIEW */}
        {screen === 'result' && selectedTest && (
          <div className="bg-white border-2 border-[#003366] rounded-xl p-6 sm:p-8 shadow-sm">
            <div className="text-center mb-6">
              <div className="inline-flex items-center justify-center w-16 h-16 rounded-full bg-green-100 text-green-700 mb-3">
                <Award className="w-9 h-9" />
              </div>
              <h2 className="text-2xl font-black text-green-700">✓ Test Completed</h2>
            </div>

            {/* Result Stats Card */}
            <div className="bg-blue-50/80 border border-blue-100 rounded-xl p-5 mb-6 text-center text-slate-800 space-y-2">
              <div className="text-sm font-semibold text-[#003366]">{selectedTest.name}</div>
              <div className="text-sm">
                Student Name: <strong>{studentName}</strong> &bull; Roll No: <strong>{rollNo}</strong>
              </div>
              <div className="text-2xl sm:text-3xl font-black text-[#003366] pt-2">
                Your Score: {score} / {selectedTest.questions.length}
              </div>
              <div className="text-base font-bold text-emerald-700">
                Percentage: {((score / selectedTest.questions.length) * 100).toFixed(2)}%
              </div>
            </div>

            {/* Google Sheet Sync Simulator Status */}
            <div className="text-center text-sm font-medium mb-6">
              {savingState === 'saving' && (
                <span className="text-amber-600 flex items-center justify-center space-x-1.5">
                  <RefreshCw className="w-4 h-4 animate-spin" />
                  <span>Saving result to Google Sheet tab...</span>
                </span>
              )}
              {savingState === 'saved' && (
                <span className="text-emerald-700 flex items-center justify-center space-x-1.5 font-bold">
                  <CheckCircle2 className="w-4 h-4" />
                  <span>✓ Result successfully recorded in Google Sheets database</span>
                </span>
              )}
            </div>

            {/* Answer Review Header */}
            <div className="border-t border-slate-200 pt-6">
              <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between mb-4 gap-2">
                <h3 className="text-lg font-bold text-[#003366]">Detailed Answer Review</h3>
                <div className="flex items-center space-x-3 text-xs font-bold">
                  <span className="flex items-center text-emerald-700">
                    <span className="w-2.5 h-2.5 rounded-full bg-emerald-600 inline-block mr-1"></span> Correct
                  </span>
                  <span className="flex items-center text-red-600">
                    <span className="w-2.5 h-2.5 rounded-full bg-red-600 inline-block mr-1"></span> Wrong
                  </span>
                  <span className="flex items-center text-amber-600">
                    <span className="w-2.5 h-2.5 rounded-full bg-amber-500 inline-block mr-1"></span> Unanswered
                  </span>
                </div>
              </div>

              {/* Review Cards */}
              <div className="space-y-4">
                {selectedTest.questions.map((question, qIdx) => {
                  const studentAns = studentAnswers[qIdx] || '';
                  const correctAns = question.answer;
                  const isCorrect = studentAns === correctAns;
                  const isUnanswered = studentAns === '';

                  let borderClass = 'border-l-6 border-l-amber-500 bg-amber-50/50';
                  if (isCorrect) {
                    borderClass = 'border-l-6 border-l-emerald-600 bg-emerald-50/40';
                  } else if (!isUnanswered) {
                    borderClass = 'border-l-6 border-l-red-500 bg-red-50/40';
                  }

                  return (
                    <div
                      key={question.id || qIdx}
                      className={`border border-slate-200 rounded-xl p-4 sm:p-5 ${borderClass}`}
                    >
                      <div className="font-bold text-slate-900 text-sm sm:text-base mb-2">
                        Question {qIdx + 1}: <MathText text={question.q} />
                      </div>

                      {question.image && (
                        <div className="my-2">
                          <img
                            src={question.image}
                            alt="Diagram"
                            className="max-h-48 rounded border border-slate-200"
                            onError={(e) => {
                              (e.target as HTMLImageElement).style.display = 'none';
                            }}
                          />
                        </div>
                      )}

                      {/* Options breakdown */}
                      <div className="space-y-1.5 my-3">
                        {question.options.map((optText, optIdx) => {
                          const letter = String.fromCharCode(65 + optIdx);
                          const isOptionCorrect = letter === correctAns;
                          const isOptionChosen = letter === studentAns;

                          let optStyle = 'p-2 rounded text-xs sm:text-sm text-slate-700';
                          if (isOptionCorrect) {
                            optStyle += ' bg-emerald-100/80 border border-emerald-300 font-bold text-emerald-900';
                          } else if (isOptionChosen && !isOptionCorrect) {
                            optStyle += ' bg-red-100/80 border border-red-300 font-bold text-red-900';
                          } else {
                            optStyle += ' bg-slate-50';
                          }

                          return (
                            <div key={optIdx} className={optStyle}>
                              <span className="font-mono mr-1.5">{letter}.</span>
                              <MathText text={optText} />
                              {isOptionCorrect && (
                                <span className="ml-2 text-emerald-700 font-bold text-xs">
                                  ✓ (Correct Answer)
                                </span>
                              )}
                              {isOptionChosen && !isOptionCorrect && (
                                <span className="ml-2 text-red-600 font-bold text-xs">
                                  ✗ (Your Wrong Answer)
                                </span>
                              )}
                              {isOptionChosen && isOptionCorrect && (
                                <span className="ml-2 text-emerald-800 font-bold text-xs">
                                  ← Your Answer
                                </span>
                              )}
                            </div>
                          );
                        })}
                      </div>

                      {/* Explanation if available */}
                      {question.explanation && (
                        <div className="mt-2 text-xs text-slate-600 bg-white p-2.5 rounded border border-slate-200 flex items-start space-x-1.5">
                          <HelpCircle className="w-4 h-4 text-blue-600 shrink-0 mt-0.5" />
                          <span>
                            <strong>Explanation:</strong> <MathText text={question.explanation} />
                          </span>
                        </div>
                      )}
                    </div>
                  );
                })}
              </div>
            </div>

            {/* Next Test Button */}
            <div className="text-center pt-8 border-t border-slate-200 mt-6">
              <button
                type="button"
                id="btn-go-next-test"
                onClick={handleGoToTestSelection}
                className="bg-[#2e7d32] hover:bg-[#1b5e20] text-white px-10 py-3.5 rounded-xl font-black text-lg transition shadow cursor-pointer"
              >
                NEXT TEST
              </button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};
